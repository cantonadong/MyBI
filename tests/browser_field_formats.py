"""Persisted field formatting, ten-row preview, and resize-driven label density."""
import os
from playwright.sync_api import sync_playwright, expect


def main():
    url = os.getenv('WORKBENCH_TEST_URL', 'http://127.0.0.1:8000')
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True, channel=os.getenv('WORKBENCH_BROWSER_CHANNEL') or None)
        page = browser.new_page(viewport={'width': 1900, 'height': 1100})
        page.add_init_script('''window.drawnText=[]; const fill=CanvasRenderingContext2D.prototype.fillText; CanvasRenderingContext2D.prototype.fillText=function(text,...args){ window.drawnText.push(String(text)); return fill.call(this,text,...args); };''')
        values = [i + .123 for i in range(30)]
        text = 'category\tcount\trate\n' + '\n'.join(f'cat{i}\t{i}\t{value}' for i, value in enumerate(values))
        result = page.request.post(url + '/api/imports/paste', data={'name': 'Field format acceptance', 'text': text})
        assert result.ok, result.text()
        dataset = result.json()
        page.goto(url)
        expect(page.get_by_test_id('active-dataset')).to_contain_text('Field format acceptance')
        page.get_by_role('button', name='＋ 柱状图', exact=True).click()
        page.get_by_label('Y 轴', exact=True).select_option('rate')
        expect(page.locator('.properties').get_by_text('格式', exact=True)).to_have_count(0)
        page.get_by_test_id('active-dataset').click()
        dialog = page.get_by_role('dialog', name='数据预览')
        expect(dialog.locator('tbody tr')).to_have_count(3)
        expect(page.get_by_label('count 数值类型')).to_have_value('integer')
        expect(page.get_by_label('rate 字段类型')).to_have_value('number')
        expect(page.get_by_label('rate 小数位数')).to_have_value('2')
        page.get_by_label('rate 数值类型').select_option('percent')
        expect(dialog.locator('tr[data-field="rate"]')).to_contain_text('12.30%')
        page.mouse.click(5, 5)
        expect(dialog).to_be_visible()
        page.get_by_role('button', name='关闭数据预览').click()
        page.get_by_test_id('active-dataset').click()
        expect(page.get_by_label('rate 数值类型')).to_have_value('decimal')
        page.get_by_label('rate 数值类型').select_option('percent')
        page.get_by_label('rate 小数位数').select_option('1')
        page.get_by_label('count 字段类型').select_option('string')
        page.get_by_role('button', name='保存', exact=True).click()
        expect(dialog).not_to_be_visible()
        page.get_by_test_id('active-dataset').click()
        expect(page.get_by_label('count 字段类型')).to_have_value('string')
        expect(page.get_by_label('rate 数值类型')).to_have_value('percent')
        expect(dialog.locator('tr[data-field="rate"]')).to_contain_text('12.3%')
        page.get_by_label('count 字段类型').select_option('number')
        page.get_by_role('button', name='取消', exact=True).click()
        page.get_by_test_id('active-dataset').click()
        expect(page.get_by_label('count 字段类型')).to_have_value('string')
        page.keyboard.press('Escape')
        expect(dialog).not_to_be_visible()
        page.get_by_label('数据标签', exact=True).check()
        page.get_by_text('选中图表：计算指标与精确布局', exact=True).click()
        width = page.get_by_label('宽度', exact=True)
        width.fill('3')
        expected = [f'{value*100:,.1f}%' for value in values]
        page.wait_for_function('expected => window.drawnText.some(t=>expected.includes(t))', arg=expected)
        page.evaluate('window.drawnText=[]')
        # Rebuild once at the settled narrow width, then resize only the canvas card.
        page.get_by_label('数据标签', exact=True).uncheck()
        page.get_by_label('数据标签', exact=True).check()
        page.wait_for_function('expected => window.drawnText.some(t=>expected.includes(t))', arg=expected)
        narrow = page.evaluate('expected => new Set(window.drawnText.filter(t=>expected.includes(t))).size', expected)
        page.evaluate('window.drawnText=[]')
        width.fill('12')
        page.wait_for_function('({expected,narrow}) => new Set(window.drawnText.filter(t=>expected.includes(t))).size > narrow', arg={'expected': expected, 'narrow': narrow})
        raw = page.request.post(url + f"/api/datasets/{dataset['id']}/view-query", data={'fields': ['rate'], 'limit': 1}).json()
        assert raw['rows'] == [{'rate': .123}]
        page.get_by_role('button', name='保存仪表板', exact=True).click()
        expect(page.get_by_role('status')).to_have_text('已保存')
        expect(page.get_by_label('打开仪表板')).not_to_have_value('')
        saved_id = page.get_by_label('打开仪表板').input_value()
        page.reload()
        expect(page.get_by_label('打开仪表板').locator(f'option[value="{saved_id}"]')).to_have_count(1)
        page.get_by_label('打开仪表板').select_option(saved_id)
        page.get_by_test_id('active-dataset').click()
        expect(page.get_by_label('rate 数值类型')).to_have_value('percent')
        expect(page.get_by_role('dialog', name='数据预览').locator('tr[data-field="rate"]')).to_contain_text('12.3%')
        page.get_by_role('button', name='关闭数据预览').click()
        page.get_by_label('图表类型', exact=True).select_option('kpi')
        expect(page.locator('.metric')).to_have_text('43,869.0%')
        page.locator('.properties').get_by_label('聚合').select_option('count')
        expect(page.locator('.metric')).to_have_text('30')
        page.get_by_label('图表类型', exact=True).select_option('table')
        expect(page.locator('.table-scroll tbody tr').first).to_contain_text('12.3%')
        browser.close()
        print('PASS: ten rows; inferred types; persisted percentage; live chart format; labels adapt on resize; KPI/table; raw values unchanged')


if __name__ == '__main__':
    main()
